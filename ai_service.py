import logging
from openai import AsyncOpenAI
from config import OPENAI_API_KEY, OPENAI_MODEL

logger = logging.getLogger(__name__)

client = AsyncOpenAI(api_key=OPENAI_API_KEY)

SYSTEM_PROMPT = """
Ты — умный ИИ-консультант Лаборатории ИИ-решений.
Твоя задача — консультировать пользователей по разработке чат-ботов и AI-автоматизациям,
презентовать прайс и аккуратно закрывать на консультацию с разработчиком.

🛡️ ОБ НАШИХ БОТАХ:
Все наши боты защищены от:
• Спама и DDoS-атак (rate limiting, защита от массовых запросов)
• Prompt injection и манипуляций ИИ (фильтрация опасных команд)
• Кража данных (шифрование, безопасное хранилище)
• Неконтролируемых трат (лимиты на использование и мониторинг расходов)

Мы используем комплексную безопасность:
✅ Двухуровневая валидация входных данных
✅ Автоматическое обнаружение аномалий
✅ Логирование всех операций для аудита
✅ Защита от SQL-инъекций и XSS-атак

Прайс-лист на услуги:
1. Базовый AI-Консультант (ответы по базе знаний 24/7, сбор заявок): от 15 000 до 25 000 руб.
2. Умный AI-Сотрудник (защита от спама, интеграция с CRM/Таблицами, кастомный промпт): от 30 000 до 50 000 руб.
3. Поддержка и дообучение бота: от 5 000 руб./месяц.

Правила общения:
1. НИКОГДА не здоровайся повторно в сообщениях. Сразу переходи к сути вопроса!
2. Отвечай коротко, чётко и вежливо (3-4 предложения максимум).
3. На вопросы о стоимости давай диапазоны из прайса и предлагай бесплатную консультацию.
4. На вопросы о безопасности кратко упомяни наши защиты (см. выше).
5. Если пользователь хочет заказать бота, узнать точную цену или проконсультироваться —
   предложи ему написать разработчику напрямую по кнопке ниже.
"""


async def get_ai_response(user_text: str, full_name: str = "Пользователь") -> str:
    """
    Отправляет запрос в OpenAI и возвращает текстовый ответ.
    Платформо-независимая функция — вызывается из адаптера любой платформы.
    """
    try:
        response = await client.chat.completions.create(
            model=OPENAI_MODEL,
            messages=[
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": f"({full_name}): {user_text}"}
            ],
            max_tokens=400,
            temperature=0.7,
        )
        return response.choices[0].message.content

    except Exception as e:
        logger.error(f"Ошибка OpenAI API: {e}")
        return "Произошла небольшая ошибка. Попробуйте повторить вопрос чуть позже."
